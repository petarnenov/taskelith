import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import ts from 'typescript';

// Generates the web SPA's control-plane types into a committed file; --check
// fails when the committed file differs from a fresh generation.

export const CONTROL_PLANE_DOCUMENT = 'packages/contracts/documents/control-plane.openapi.json';
export const WEB_API_TYPES = 'apps/web/src/generated/control-plane.ts';
const BANNER = '// Generated by scripts/generate-web-api-types.ts; do not edit.\n';

// The OpenAPI descriptions stay in the document; dropping them from the
// output keeps the committed file free of long generated comments.
export async function webApiTypes(document: OpenAPI3): Promise<string> {
  const generated = astToString(await openapiTS(document));
  const source = ts.createSourceFile('control-plane.ts', generated, ts.ScriptTarget.Latest, false, ts.ScriptKind.TS);
  return BANNER + ts.createPrinter({ removeComments: true }).printFile(source);
}

export async function staleWebApiTypes(root: string): Promise<boolean> {
  const committed = join(root, WEB_API_TYPES);
  const expected = await webApiTypes(readJson(join(root, CONTROL_PLANE_DOCUMENT)));
  return !existsSync(committed) || readFileSync(committed, 'utf8') !== expected;
}

function readJson(path: string): OpenAPI3 {
  return JSON.parse(readFileSync(path, 'utf8')) as OpenAPI3;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  if (process.argv[2] === '--check') {
    if (await staleWebApiTypes(root)) {
      console.error(`${WEB_API_TYPES} is stale; run npm run generate:web-api-types and commit it.`);
      process.exit(1);
    }
    console.log(`${WEB_API_TYPES} matches ${CONTROL_PLANE_DOCUMENT}.`);
  } else {
    writeFileSync(join(root, WEB_API_TYPES), await webApiTypes(readJson(join(root, CONTROL_PLANE_DOCUMENT))));
    console.log(`Wrote ${WEB_API_TYPES}.`);
  }
}
