import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Parser, type Diagnostic } from '@asyncapi/parser';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

// Generates wire contract types and schema bundles (G1 decision D3 (a)) into
// the git-ignored src/generated/ before the workspace build.

export type ContractKind = 'openapi' | 'asyncapi';

export interface ContractDocument {
  readonly kind: ContractKind;
  readonly path: string;
}

export const CONTRACT_DOCUMENTS: readonly ContractDocument[] = Object.freeze([
  { kind: 'openapi', path: 'packages/contracts/documents/sdlc.openapi.json' },
  { kind: 'asyncapi', path: 'packages/contracts/documents/sdlc.asyncapi.json' },
  { kind: 'openapi', path: 'packages/contracts/documents/execution.openapi.json' },
  { kind: 'asyncapi', path: 'packages/contracts/documents/execution.asyncapi.json' },
]);

const OUTPUT_DIR = 'packages/contracts/src/generated';
const BANNER = '// Generated by scripts/generate-contracts.ts from the contract documents; do not edit.\n';
const COMPONENT_REF = /"#\/components\/schemas\/([^"]+)"/g;

type Schemas = Record<string, unknown>;

export interface SchemaSource {
  readonly path: string;
  readonly schemas: Schemas;
}

// Diagnostics of severity error (0) or warning (1) fail the build; information
// and hints, such as a newer AsyncAPI version being available, do not.
export function blockingDiagnostics(diagnostics: readonly Diagnostic[]): string[] {
  return diagnostics
    .filter((diagnostic) => diagnostic.severity <= 1)
    .map((diagnostic) => `${diagnostic.path.join('/') || '/'}: ${diagnostic.message}`);
}

// Moves the component schemas of a document into one standalone JSON Schema
// whose references point at its own definitions keyword.
export function schemaBundle(id: string, definitionsKeyword: '$defs' | 'definitions', schemas: Schemas): Schemas {
  const rewritten = JSON.parse(JSON.stringify(schemas).replace(COMPONENT_REF, `"#/${definitionsKeyword}/$1"`));
  return { $id: id, [definitionsKeyword]: rewritten };
}

// A root schema whose properties name every definition, so that the type
// generator emits one interface mapping each schema name to its type.
export function namedTypesSchema(title: string, definitions: Schemas): JSONSchema {
  const names = Object.keys(definitions);
  return {
    title,
    type: 'object',
    additionalProperties: false,
    required: names,
    properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/definitions/${name}` }])),
    definitions: definitions as JSONSchema['definitions'],
  };
}

// One vocabulary across documents: a component name used by several documents
// must name the same schema, so that each generated name has one type.
export function mergeSchemas(sources: readonly SchemaSource[]): Schemas {
  const merged: Schemas = {};
  const origins = new Map<string, string>();
  for (const { path, schemas } of sources) {
    for (const [name, schema] of Object.entries(schemas)) {
      const origin = origins.get(name);
      if (origin !== undefined && JSON.stringify(merged[name]) !== JSON.stringify(schema)) {
        throw new Error(`The schema ${name} of ${path} differs from the one of ${origin}`);
      }
      origins.set(name, origin ?? path);
      merged[name] = schema;
    }
  }
  return merged;
}

export interface OpenapiSource {
  readonly path: string;
  readonly document: { readonly paths?: Schemas; readonly components: { readonly schemas: Schemas; readonly securitySchemes?: Schemas } };
}

export interface MergedOpenapi {
  readonly openapi: string;
  readonly info: Schemas;
  readonly paths: Schemas;
  readonly components: { readonly schemas: Schemas; readonly securitySchemes: Schemas };
}

// Joins the paths and components of OpenAPI documents into one document for
// the type generator; a path defined twice is an error.
export function mergeOpenapi(sources: readonly OpenapiSource[]): MergedOpenapi {
  const paths: Schemas = {};
  for (const { path, document } of sources) {
    for (const [route, item] of Object.entries(document.paths ?? {})) {
      if (route in paths) throw new Error(`The path ${route} of ${path} is defined by another document`);
      paths[route] = item;
    }
  }
  return {
    openapi: '3.1.0',
    info: { title: 'Taskelith HTTP contracts', version: '0.0.0' },
    paths,
    components: {
      schemas: mergeSchemas(sources.map(({ path, document }) => ({ path, schemas: document.components.schemas }))),
      securitySchemes: Object.assign({}, ...sources.map(({ document }) => document.components.securitySchemes ?? {})),
    },
  };
}

async function asyncapiSchemas(path: string): Promise<Schemas> {
  const { document, diagnostics } = await new Parser().parse(readFileSync(path, 'utf8'));
  const problems = blockingDiagnostics(diagnostics);
  if (document === undefined || problems.length > 0) throw new Error(`${path} is not a valid AsyncAPI document:\n${problems.join('\n')}`);
  return JSON.parse(readFileSync(path, 'utf8')).components.schemas;
}

function documentsOf(kind: ContractKind): ContractDocument[] {
  return CONTRACT_DOCUMENTS.filter((document) => document.kind === kind);
}

async function generate(root: string): Promise<void> {
  const openapi = mergeOpenapi(documentsOf('openapi').map(({ path }) => ({ path, document: JSON.parse(readFileSync(join(root, path), 'utf8')) })));
  const messageSources: SchemaSource[] = [];
  for (const { path } of documentsOf('asyncapi')) messageSources.push({ path, schemas: await asyncapiSchemas(join(root, path)) });
  const messageSchemas = mergeSchemas(messageSources);
  const messageDefinitions = JSON.parse(JSON.stringify(messageSchemas).replace(COMPONENT_REF, '"#/definitions/$1"'));

  const httpTypes = astToString(await openapiTS(openapi as unknown as OpenAPI3));
  const messageTypes = await compile(namedTypesSchema('MessageSchemas', messageDefinitions), 'MessageSchemas', {
    bannerComment: '',
    format: false,
    additionalProperties: false,
  });
  const bundles = [
    `export const HTTP_SCHEMAS = ${JSON.stringify(schemaBundle('taskelith:contracts/http', '$defs', openapi.components.schemas), null, 2)};`,
    `export const MESSAGE_SCHEMAS = ${JSON.stringify(schemaBundle('taskelith:contracts/messages', 'definitions', messageSchemas), null, 2)};`,
  ].join('\n\n');

  const output = join(root, OUTPUT_DIR);
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, 'http-types.ts'), `${BANNER}${httpTypes}`);
  writeFileSync(join(output, 'message-types.ts'), `${BANNER}${messageTypes}`);
  writeFileSync(join(output, 'schemas.ts'), `${BANNER}${bundles}\n`);
}

if (import.meta.main) {
  await generate(process.cwd());
  console.log(`Generated contract types and schemas in ${OUTPUT_DIR}.`);
}
