import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Parser, type Diagnostic } from '@asyncapi/parser';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

// Generates wire contract types and schema bundles (G1 decision D3 (a)) into
// the git-ignored src/generated/ before the workspace build.

export const CONTRACT_DOCUMENTS = Object.freeze({
  openapi: 'packages/contracts/documents/sdlc.openapi.json',
  asyncapi: 'packages/contracts/documents/sdlc.asyncapi.json',
});

const OUTPUT_DIR = 'packages/contracts/src/generated';
const BANNER = '// Generated by scripts/generate-contracts.ts from the contract documents; do not edit.\n';
const COMPONENT_REF = /"#\/components\/schemas\/([^"]+)"/g;

type Schemas = Record<string, unknown>;

// Diagnostics of severity error (0) or warning (1) fail the build; information
// and hints, such as a newer AsyncAPI version being available, do not.
export function blockingDiagnostics(diagnostics: readonly Diagnostic[]): string[] {
  return diagnostics
    .filter((diagnostic) => diagnostic.severity <= 1)
    .map((diagnostic) => `${diagnostic.path.join('/') || '/'}: ${diagnostic.message}`);
}

// Moves the component schemas of a document into one standalone JSON Schema
// whose references point at its own definitions keyword.
export function schemaBundle(id: string, definitionsKeyword: '$defs' | 'definitions', schemas: Schemas): Schemas {
  const rewritten = JSON.parse(JSON.stringify(schemas).replace(COMPONENT_REF, `"#/${definitionsKeyword}/$1"`));
  return { $id: id, [definitionsKeyword]: rewritten };
}

// A root schema whose properties name every definition, so that the type
// generator emits one interface mapping each schema name to its type.
export function namedTypesSchema(title: string, definitions: Schemas): JSONSchema {
  const names = Object.keys(definitions);
  return {
    title,
    type: 'object',
    additionalProperties: false,
    required: names,
    properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/definitions/${name}` }])),
    definitions: definitions as JSONSchema['definitions'],
  };
}

async function asyncapiSchemas(path: string): Promise<Schemas> {
  const { document, diagnostics } = await new Parser().parse(readFileSync(path, 'utf8'));
  const problems = blockingDiagnostics(diagnostics);
  if (document === undefined || problems.length > 0) throw new Error(`${path} is not a valid AsyncAPI document:\n${problems.join('\n')}`);
  return JSON.parse(readFileSync(path, 'utf8')).components.schemas;
}

async function generate(root: string): Promise<void> {
  const openapiPath = join(root, CONTRACT_DOCUMENTS.openapi);
  const openapi = JSON.parse(readFileSync(openapiPath, 'utf8'));
  const messageSchemas = await asyncapiSchemas(join(root, CONTRACT_DOCUMENTS.asyncapi));
  const messageDefinitions = JSON.parse(JSON.stringify(messageSchemas).replace(COMPONENT_REF, '"#/definitions/$1"'));

  const httpTypes = astToString(await openapiTS(openapi));
  const messageTypes = await compile(namedTypesSchema('MessageSchemas', messageDefinitions), 'MessageSchemas', {
    bannerComment: '',
    format: false,
    additionalProperties: false,
  });
  const bundles = [
    `export const HTTP_SCHEMAS = ${JSON.stringify(schemaBundle('taskelith:contracts/sdlc-http', '$defs', openapi.components.schemas), null, 2)};`,
    `export const MESSAGE_SCHEMAS = ${JSON.stringify(schemaBundle('taskelith:contracts/sdlc-messages', 'definitions', messageSchemas), null, 2)};`,
  ].join('\n\n');

  const output = join(root, OUTPUT_DIR);
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, 'http-types.ts'), `${BANNER}${httpTypes}`);
  writeFileSync(join(output, 'message-types.ts'), `${BANNER}${messageTypes}`);
  writeFileSync(join(output, 'schemas.ts'), `${BANNER}${bundles}\n`);
}

if (import.meta.main) {
  await generate(process.cwd());
  console.log(`Generated contract types and schemas in ${OUTPUT_DIR}.`);
}
